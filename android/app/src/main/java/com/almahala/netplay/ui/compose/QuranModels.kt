package com.almahala.netplay.ui.compose

enum class QuranRoomCouncilType(val title: String) {
    SURAH("تلاوة سورة"),
    JUZ("تلاوة جزء"),
    KHATMAH("ختمة قرآنية")
}

enum class QuranRoomVisibility(val title: String) {
    PUBLIC("غرفة عامة"),
    PRIVATE("غرفة خاصة")
}

enum class QuranUserRole(val title: String, val badgeColorHex: Long) {
    HOST("مالك الغرفة", 0xFF10B981),
    ADMIN("مدير", 0xFF3B82F6),
    MODERATOR("مشرف", 0xFFF59E0B),
    SPEAKER("متحدث", 0xFF8B5CF6),
    LISTENER("مستمع", 0xFF64748B)
}

data class QuranSurah(
    val id: Int,
    val name: String,
    val nameEn: String,
    val revelationType: String,
    val versesCount: Int,
    val juzNumber: Int
)

data class QuranReader(
    val id: String,
    val name: String,
    val style: String,
    val imageUrl: String,
    val audioBaseUrl: String = ""
)

data class QuranAyah(
    val number: Int,
    val textUthmani: String,
    val tafsir: String = ""
)

data class QuranRoomUser(
    val id: String,
    val name: String,
    val avatarUrl: String,
    var role: QuranUserRole,
    var isMuted: Boolean = false,
    var isCameraOn: Boolean = false,
    var localVolume: Float = 1.0f,
    var isSpeaking: Boolean = false
)

data class QuranChatMessage(
    val id: String,
    val senderId: String,
    val senderName: String,
    val senderAvatar: String,
    val senderRole: QuranUserRole,
    val text: String,
    val timestamp: String,
    val isAyahShare: Boolean = false
)

data class QuranLiveRoom(
    val roomId: String,
    val roomCode: String,
    val hostUserId: String,
    var name: String,
    var password: String = "",
    var visibility: QuranRoomVisibility = QuranRoomVisibility.PUBLIC,
    var reader: QuranReader,
    var councilType: QuranRoomCouncilType = QuranRoomCouncilType.SURAH,
    var currentJuz: Int = 1,
    var currentSurah: QuranSurah,
    var currentAyahNumber: Int = 1,
    var listenersCount: Int = 24,
    var isPlaying: Boolean = true,
    var playbackPositionMs: Long = 75000L,
    var khatmahProgressPercent: Int = 5,
    var isChatEnabled: Boolean = true,
    var isVoiceEnabled: Boolean = true,
    var isCameraEnabled: Boolean = false,
    var isRoomLocked: Boolean = false
)

